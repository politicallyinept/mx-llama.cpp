#!/usr/bin/env bash
# Build the SUMW CPU seal: extract the REAL production functions from the
# worktree sources (no mirrors - an extraction miss is itself the falsification
# signal when the change is reverted), generate seal_gen.h, compile.
set -euo pipefail
WT=${1:-/root/wt-sumw}
QR=$WT/ggml/src/ggml-cuda/q8_repack
OUT=$(cd "$(dirname "$0")" && pwd)
GEN=$OUT/seal_gen.h
: > "$GEN"

extract() { # file regex-to-end-at-^}
    awk "/$2/,/^}/" "$1"
}
extract_to() { # file regex-to-end-at-^};
    awk "/$2/,/^};/" "$1"
}
emit() { printf '%s\n' "$1" >> "$GEN"; }

emit "// GENERATED by build_seal.sh from $WT - do not edit."
emit "#include <cstdint>"
emit "#include <cstddef>"
emit "#include <cstring>"
emit "#include <cstdlib>"
emit "#include <cassert>"
emit "#include <cstdio>"
emit "#define __device__"
emit "#define __host__"
emit "#define __forceinline__ inline"
emit "#define __restrict__"
emit "#define GGML_ASSERT(x) assert(x)"
emit "#define GGML_ABORT(...) do { fprintf(stderr, \"ABORT: \"); fprintf(stderr, __VA_ARGS__); fputc(10, stderr); abort(); } while (0)"
emit "#define GGML_LOG_WARN(...) do { fprintf(stderr, \"WARN: \"); fprintf(stderr, __VA_ARGS__); fputc(10, stderr); } while (0)"
emit "#define GGML_UNUSED(x) (void)(x)"
emit "#include \"w4a4-profile.h\""   // repack_sumw_plane_on now reads the resolved profile knobs
emit "struct uint4 { uint32_t x, y, z, w; };"
emit "typedef enum { GGML_TYPE_Q4_0 = 2, GGML_TYPE_Q4_1 = 3, GGML_TYPE_Q5_0 = 4, GGML_TYPE_Q5_1 = 5, GGML_TYPE_Q4_K = 12, GGML_TYPE_Q5_K = 13, GGML_TYPE_Q6_K = 14, GGML_TYPE_Q8_0 = 8, GGML_TYPE_IQ4_NL = 20, GGML_TYPE_MXFP4 = 39 } ggml_type;"
emit "struct block_q4_0   { uint16_t d; uint8_t qs[16]; };"
emit "struct block_iq4_nl { uint16_t d; uint8_t qs[16]; };"
emit "bool repack_sumw_plane_on();"   // fwd: repack_gcn_nbytes calls it before its definition
emit "template <ggml_type T> struct rp_traits;"
emit ""
emit "// ---- extracted: repack_qs_stride / repack_qs_row_stride (repack-common.cuh)"
emit "template <typename T>" >> "$GEN"
extract "$QR/repack-common.cuh" "static __host__ __device__ inline T repack_qs_stride" >> "$GEN"
emit "template <typename T>" >> "$GEN"
extract "$QR/repack-common.cuh" "static __host__ __device__ inline T repack_qs_row_stride" >> "$GEN"
emit ""
emit "// ---- extracted: repack_gcn_nbytes (repack-common.cuh)"
extract "$QR/repack-common.cuh" "static inline size_t repack_gcn_nbytes" >> "$GEN"
emit ""
emit "// ---- extracted: rp_traits<Q4_0> incl. geom (repack-common.cuh)"
extract_to "$QR/repack-common.cuh" "^template <> struct rp_traits<GGML_TYPE_Q4_0>" >> "$GEN"
emit ""
emit "// ---- extracted: nib_sum_u4 (repack-kernels.cuh) - the inline reference"
extract "$QR/repack-kernels.cuh" "static __device__ __forceinline__ uint32_t nib_sum_u4" >> "$GEN"
emit ""
emit "// ---- extracted: repack_sumw_plane_on (repack-common.cu) - the gate"
extract "$QR/repack-common.cu" "^bool repack_sumw_plane_on" >> "$GEN"
emit ""
emit "// ---- extracted: repack_iq4nl_host (repack-common.cu)"
extract "$QR/repack-common.cu" "^void repack_iq4nl_host" >> "$GEN"
emit ""
emit "// ---- extracted: repack_q40_host (repack-common.cu) - the converter under test"
extract "$QR/repack-common.cu" "^void repack_q40_host" >> "$GEN"
emit ""

fail=0
for sym in "repack_qs_stride" "repack_qs_row_stride" "repack_gcn_nbytes" "nib_sum_u4" "repack_iq4nl_host" "repack_sumw_plane_on" "repack_q40_host" "swplane_off"; do
    if ! grep -q "$sym" "$GEN"; then
        echo "EXTRACT-MISS: '$sym' not found in $WT sources - the SUMW change is absent/reverted (pre-change state: no plane, no converter)." >&2
        fail=1
    fi
done

# Textual tie: the device repack kernel must carry the SAME signed formula as the
# host converter (the seal cannot execute __global__ code on CPU).
if ! grep -qF "(int16_t) ((int) nib - 256)" "$QR/buffer.cu"; then
    echo "EXTRACT-MISS: repack_q40_kernel formula '(int16_t) ((int) nib - 256)' not found in buffer.cu - device repack does not write the SIGNED plane." >&2
    fail=1
fi
# Textual tie: the epilogue reader must sign-extend int16 (load_sw).
if ! grep -qF "(int32_t) reinterpret_cast<const int16_t *>" "$QR/repack-common.cuh"; then
    echo "EXTRACT-MISS: load_sw int16 sign-extend read not found in repack-common.cuh - epilogue does not read the plane." >&2
    fail=1
fi
[ "$fail" = 0 ] || exit 1

g++ -std=c++17 -O1 -I "$QR" -I "$OUT" -o "$OUT/seal_sumw_plane" "$OUT/seal_sumw_plane.cc"
echo "seal built: $OUT/seal_sumw_plane"
